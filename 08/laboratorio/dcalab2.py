def tempo(nome, tipo=None):
    #Retorna um tempo (min) conforme TEMPOS.
       #- Se for tupla (a,b): sorteia uniforme entre a e b.
       #- Se for dict por tipo: usa chave 'Urgente'/'Rotina'.
       #- Se for número: devolve fixo.

    val = TEMPOS[nome]
    if isinstance(val, dict):
        val2 = val[tipo]
        if isinstance(val2, tuple):
            return random.uniform(*val2)
        return float(val2)
    if isinstance(val, tuple):
        return random.uniform(*val)
    return float(val)

def criaChegadas(env, taxa, tec_lab, proporcao,p_coleta_externa,monitor):
    contaChegadas = 0
    tipos = list(proporcao.keys())
    pesos = list(proporcao.values())

    while True:
        # espera até a próxima chegada (exponencial)
        #yield env.timeout(random.expovariate(1 / taxa))
        yield env.timeout(taxa)
        contaChegadas += 1

        # escolhe tipo segundo a proporção
        tipo = random.choices(tipos, weights=pesos, k=1)[0]

        # sorteia se é coleta própria
        coleta_externa = random.random() < p_coleta_externa

        # nomeia o pedido (podemos mudar pra input() depois)
        pedido = f"Exame_{contaChegadas}"

        #Registra chegada
        monitor.inicio(pedido,env.now)
        monitor.log(env,pedido,"Chegada")


        if coleta_externa:
            print(f"{env.now:.1f}: {pedido} Chegou! | ({tipo}, Coleta já realizada pelo PACIENTE)")
            env.process(EntregaAmostra(env, pedido, tipo, triagista,monitor))
        else:
            print(f"{env.now:.1f}: {pedido} Chegou! | ({tipo}, Coleta no LABORATÓRIO)")
            env.process(NomeacaoPotes(env, pedido, tipo, tec_lab,monitor))

def NomeacaoPotes(env, pedido, tipo, tec_lab, monitor):
    monitor.log(env, pedido, "Inicio nomeação de potes", "tec_lab")

    with tec_lab.request() as req:
        t_entrada_fila = env.now
        fila_atual = len(tec_lab.queue)
        monitor.registrar_fila("tec_lab", fila_atual, env.now)

        yield req  # aguarda o recurso
        tempo_espera = env.now - t_entrada_fila
        monitor.registrar_tempo_espera("tec_lab", tempo_espera)

        inicio_servico = env.now
        monitor.log(env, pedido, "Tec_lab iniciou nomeação de potes", "tec_lab")
        print(f"{env.now:.1f}: Nomeando potes para {pedido}. | ({tipo})")

        duracao_servico = tempo("nomeacao_potes")
        yield env.timeout(duracao_servico)
        fim_servico = env.now

        monitor.registrar_tempo_servico("tec_lab", duracao_servico)
        monitor.registrar_uso_recurso("tec_lab", inicio_servico, fim_servico)

        monitor.log(env, pedido, "Tec_lab finalizou nomeação de potes", "tec_lab")
        print(f"{env.now:.1f}: Nomeação de potes finalizada para {pedido}. | ({tipo})")

        env.process(TransporteLabParaLeito(env, pedido, tipo, tec_lab, monitor))


