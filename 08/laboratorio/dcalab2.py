def ColetaAmostra(env, pedido, tipo, tec_lab,monitor):
    monitor.log(env,pedido,"Inicio coleta","tec_lab")
    # mapa numérico de prioridade (menor = atende antes)
    prioridade = {"Urgente": 0, "Rotina": 1}
    prio = prioridade.get(tipo, 1)

    # solicita o recurso com prioridade
    with tec_lab.request(priority=prio) as req:

        #REGISTRO/MONITORAMENTO DE FILAS
        t_entrada_fila = env.now
        fila_atual = len(tec_lab.queue)
        monitor.registrar_fila("tec_lab", fila_atual, env.now)

        yield req  # aguarda até conseguir o recurso

        #tempo de espera
        tempo_espera = env.now - t_entrada_fila
        monitor.registrar_tempo_espera("tec_lab", tempo_espera)

        inicio_servico = env.now
        monitor.log(env,pedido,"Tec_lab iniciou coleta","tec_lab")
        print(f"{env.now:.1f}: Coletando {pedido}. | ({tipo}, Prioridade = {prio})")

        t = tempo("coleta", tipo)
        yield env.timeout(t)

        fim_servico = env.now #registra final do serviço

        monitor.registrar_tempo_servico("tec_lab", t)
        monitor.registrar_uso_recurso("tec_lab", inicio_servico, fim_servico)

        monitor.log(env,pedido,"Tec_lab finalizou coleta","tec_lab")
        print(f"{env.now:.1f}: {pedido} coletado! | ({tipo}) - durou {t} min")

        env.process(Transporte(env,pedido,tec_lab,tipo,monitor))


