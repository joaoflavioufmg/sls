#cria uma classe monitor, que irá monitora tempo e emitir relatórios pra cada entidade de exame
class Monitor:
    def __init__(self):
        self.registros = []
        self.tempos_totais = {}
        self.filas = {}

        # Atributos pra computar fila e uso do recurso
        self.tempo_uso_recurso = {}
        self.ocupacao_recurso = {}
        self.fila_tam = {}          # tamanho da fila ao longo do tempo
        self.tempo_espera = {}      # tempos de espera (para média)
        self.tempo_servico = {}     # tempos de atendimento



    def log(self, env, pedido, evento, recurso=None):
        """Registra cada evento relevante"""
        self.registros.append({
            "tempo": env.now,
            "pedido": pedido,
            "evento": evento,
            "recurso": recurso
        })

    def inicio(self, pedido, tempo):
        self.tempos_totais[pedido] = {"inicio": tempo, "fim": None}

    def fim(self, pedido, tempo):
        if pedido in self.tempos_totais:
            self.tempos_totais[pedido]["fim"] = tempo

    def tempo_total(self, pedido):
        t = self.tempos_totais.get(pedido)
        if t and t["fim"] is not None:
            return t["fim"] - t["inicio"]
        return None

      # USOS RECUROS E FILAS
    def registrar_uso_recurso(self, recurso, inicio, fim):
        """Guarda o tempo total de uso de um recurso."""
        duracao = fim - inicio
        if recurso not in self.tempo_uso_recurso:
            self.tempo_uso_recurso[recurso] = 0
        self.tempo_uso_recurso[recurso] += duracao

    def registrar_fila(self, recurso, tamanho, tempo):
        """Registra tamanho da fila em um momento específico."""
        if recurso not in self.fila_tam:
            self.fila_tam[recurso] = []
        self.fila_tam[recurso].append((tempo, tamanho))

    def registrar_tempo_espera(self, recurso, tempo_espera):
        """Registra tempo em fila de um exame."""
        if recurso not in self.tempo_espera:
            self.tempo_espera[recurso] = []
        self.tempo_espera[recurso].append(tempo_espera)

    def registrar_tempo_servico(self, recurso, tempo_servico):
        """Registra tempo de atendimento de um exame."""
        if recurso not in self.tempo_servico:
            self.tempo_servico[recurso] = []
        self.tempo_servico[recurso].append(tempo_servico)



